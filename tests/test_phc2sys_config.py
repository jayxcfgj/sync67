#!/usr/bin/env python3
"""Regression-Tests fuer phc2sys-Default (Config-Snapshot + CLI-Flags).

Covered:
  1) core/phc2sys_default.cfg existiert und enthaelt die 4 Keys
  2) create_default() schreibt den Snapshot (nicht nur den Header)
  3) reset_to_default() stellt Snapshot + .bak her (statt zu leeren)
  4) meta.default_for(key) liefert den Snapshot-Wert (Default:-Label)
  5) Dialog-Labels nutzen die Snapshot-Defaults
  6) meta.CLI_DEFAULTS = die UI-CLI-Flags als Default-Quelle
  7) Dialog-Reset stellt Datei UND CLI-Flags (QSettings) wieder her
  8) Fehlender Snapshot -> Phc2sysConfigError, Datei bleibt unangetastet
  9) Erst-Erstellung -> Dialog -> Save verliert keine Werte

Run:   python3 tests/test_phc2sys_config.py
Exit:  0 = alle Checks ok, 1 = mindestens ein Check fehlgeschlagen

Root-frei, ohne Display (offscreen), schreibt NUR in Temp-Verzeichnisse;
die QSettings-CLI-Keys werden im finally zurueckgesetzt.
Erweiterung: neue check_*()-Funktion in main() hinzufuegen.
"""
import os
import sys
import tempfile

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)  # sonst greift "import core..." nicht

from PyQt6.QtCore import QSettings
from PyQt6.QtWidgets import QApplication, QLabel, QMessageBox

from core.phc2sys_config import Phc2sysConfig
from core import phc2sys_config_meta as meta
from ui.phc2sys_config_dialog import Phc2sysConfigDialog

SNAPSHOT_PATH = os.path.join(REPO, "core", "phc2sys_default.cfg")
SNAPSHOT = {
    "first_step_threshold": 1,
    "sanity_freq_limit": 0,
    "step_threshold": 1,
    "uds_address": "/var/run/ptp/ptp4l",
}
CLI_KEYS = ("auto_mode", "sync_realtime", "wait_ptp4l", "summary_updates",
            "source_device", "sink_device", "pps_device", "leap_seconds")
CLI_DEFAULTS_EXPECTED = {
    "auto_mode": True,
    "sync_realtime": "single (-r)",
    "wait_ptp4l": True,
    "summary_updates": 0,
    "sink_device": "CLOCK_REALTIME",
    "pps_device": "",
    "leap_seconds": "",
}
FAILS = []


def check(name, cond, detail=""):
    print(f"  {'ok  ' if cond else 'FAIL'} {name}"
          + (f" -> {detail}" if not cond else ""))
    if not cond:
        FAILS.append(f"{name} ({detail})")


def load(path):
    cfg = Phc2sysConfig()
    cfg.load(path)
    return cfg


def temp_config():
    """Temp-Config wie der aktuelle Stand (Snapshot-Inhalt, unabhaengig
    davon, ob die Repo-Default-Datei schon existiert)."""
    path = os.path.join(tempfile.mkdtemp(), "phc2sys.conf")
    with open(path, "w") as f:
        f.write("# phc2sys.conf - generated by sync67\n\n[global]\n")
        for key, val in SNAPSHOT.items():
            f.write(f"{key} {val}\n")
    return path


def check_snapshot_file():
    print("1) core/phc2sys_default.cfg existiert mit den 4 Keys")
    check("Snapshot-Datei vorhanden", os.path.exists(SNAPSHOT_PATH),
          SNAPSHOT_PATH)
    if not os.path.exists(SNAPSHOT_PATH):
        return
    cfg = load(SNAPSHOT_PATH)
    for key, want in SNAPSHOT.items():
        got = cfg.get(key)
        check(f"{key} = {want}", got == want, f"got {got!r}")


def check_create_default():
    print("2) create_default() schreibt den Snapshot")
    path = os.path.join(tempfile.mkdtemp(), "phc2sys.conf")
    Phc2sysConfig().create_default(path)
    cfg = load(path)
    for key, want in SNAPSHOT.items():
        got = cfg.get(key)
        check(f"{key} = {want}", got == want, f"got {got!r}")


def check_reset_restores():
    print("3) reset_to_default() stellt Snapshot + .bak her")
    path = temp_config()
    cfg = load(path)
    cfg.set("first_step_threshold", 5)
    cfg.set("domainNumber", 0)
    cfg.save()
    cfg.reset_to_default()
    check("in-memory neu geladen (first_step_threshold=1)",
          cfg.get("first_step_threshold") == 1,
          f"got {cfg.get('first_step_threshold')!r}")
    check(".bak angelegt", os.path.exists(path + ".bak"))
    again = load(path)
    for key, want in SNAPSHOT.items():
        got = again.get(key)
        check(f"{key} = {want}", got == want, f"got {got!r}")
    check("zusaetzlicher Key ist weg", again.get("domainNumber") is None,
          f"got {again.get('domainNumber')!r}")


def check_default_for():
    print("4) meta.default_for(key) -> Snapshot-Wert")
    fn = getattr(meta, "default_for", None)
    check("default_for existiert", callable(fn))
    if not callable(fn):
        return
    for key, want in SNAPSHOT.items():
        got = fn(key)
        check(f"default_for({key}) = {want}", got == want, f"got {got!r}")
    got = fn("update_interval")
    check("Nicht-Snapshot-Key faellt auf Builtin zurueck",
          got == meta.BUILTIN_DEFAULTS.get("update_interval"),
          f"got {got!r}")


def check_dialog_labels():
    print("5) Dialog-Labels nutzen die Snapshot-Defaults")
    cfg = load(temp_config())
    dlg = Phc2sysConfigDialog(cfg, None)
    for key, want in SNAPSHOT.items():
        entry = dlg._widgets.get(key)
        got = entry[1] if entry else None
        check(f"Label-Default {key} = {want}", got == want, f"got {got!r}")
    texts = [lbl.text() for lbl in dlg.findChildren(QLabel)]
    check("'Default: 1' gerendert", "Default: 1" in texts, str(texts))
    check("'Default: /var/run/ptp/ptp4l' gerendert",
          "Default: /var/run/ptp/ptp4l" in texts, str(texts))
    dlg.close()


def check_cli_defaults():
    print("6) meta.CLI_DEFAULTS = UI-CLI-Flags")
    got = getattr(meta, "CLI_DEFAULTS", None)
    check("CLI_DEFAULTS existiert", isinstance(got, dict))
    if not isinstance(got, dict):
        return
    for key, want in CLI_DEFAULTS_EXPECTED.items():
        check(f"CLI_DEFAULTS[{key}] = {want!r}", got.get(key) == want,
              f"got {got.get(key)!r}")


def check_dialog_reset():
    print("7) Dialog-Reset stellt Datei + CLI-Flags (QSettings) wieder her")
    path = temp_config()
    cfg = load(path)
    cfg.set("first_step_threshold", 5)
    cfg.save()
    qs = QSettings("sync67", "phc2sys_settings")
    backup = {k: (qs.contains(k), qs.value(k)) for k in CLI_KEYS}
    try:
        qs.setValue("auto_mode", False)
        qs.setValue("summary_updates", 9)
        dlg = Phc2sysConfigDialog(cfg, None)
        dlg._on_reset()

        again = load(path)
        for key, want in SNAPSHOT.items():
            got = again.get(key)
            check(f"Datei: {key} = {want}", got == want, f"got {got!r}")
        w = dlg._widgets["first_step_threshold"][0]
        check("Widget zurueckgesetzt", w.text() == "1", f"got {w.text()!r}")
        check("QSettings auto_mode wieder True",
              qs.value("auto_mode", type=bool) is True,
              repr(qs.value("auto_mode")))
        check("QSettings summary_updates wieder 0",
              qs.value("summary_updates", type=int) == 0,
              repr(qs.value("summary_updates")))
        dlg.close()
    finally:
        for key, (had, val) in backup.items():
            if had:
                qs.setValue(key, val)
            else:
                qs.remove(key)


def check_reset_missing_snapshot():
    print("8) Fehlender Snapshot -> Fehler, Datei bleibt unangetastet")
    from core import phc2sys_config as cfg_mod
    path = temp_config()
    cfg = load(path)
    before = open(path).read()
    old = cfg_mod.DEFAULT_CFG_PATH
    cfg_mod.DEFAULT_CFG_PATH = os.path.join(REPO, "core", "does_not_exist.cfg")
    try:
        raised = False
        try:
            cfg.reset_to_default()
        except cfg_mod.Phc2sysConfigError:
            raised = True
        check("Phc2sysConfigError geworfen", raised)
        check("Datei unangetastet", open(path).read() == before)
    finally:
        cfg_mod.DEFAULT_CFG_PATH = old


def check_save_roundtrip():
    print("9) Erst-Erstellung -> Dialog -> Save verliert keine Werte")
    qs = QSettings("sync67", "phc2sys_settings")
    backup = {k: (qs.contains(k), qs.value(k)) for k in CLI_KEYS}
    try:
        path = os.path.join(tempfile.mkdtemp(), "phc2sys.conf")
        Phc2sysConfig().create_default(path)
        dlg = Phc2sysConfigDialog(load(path), None)
        dlg._on_save()
        dlg.close()
        again = load(path)
        for key, want in SNAPSHOT.items():
            got = again.get(key)
            check(f"{key} = {want}", got == want, f"got {got!r}")
    finally:
        for key, (had, val) in backup.items():
            if had:
                qs.setValue(key, val)
            else:
                qs.remove(key)


def main():
    app = QApplication.instance() or QApplication([])
    QMessageBox.warning = staticmethod(
        lambda *a, **k: QMessageBox.StandardButton.Yes)

    check_snapshot_file()
    check_create_default()
    check_reset_restores()
    check_default_for()
    check_dialog_labels()
    check_cli_defaults()
    check_dialog_reset()
    check_reset_missing_snapshot()
    check_save_roundtrip()

    print("FAILS: NONE" if not FAILS else f"FAILS: {FAILS}")
    sys.exit(1 if FAILS else 0)


if __name__ == "__main__":
    main()
